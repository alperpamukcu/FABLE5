"""The author's Nano Banana scene batch (2026-08-18) -> game-ready assets.

14 v3 SS11.E's post chain, run against the batch the author generated by hand:
crop -> area-downscale -> key -> quantize to the 55 -> binary alpha -> ship.

QUANTIZE IS OFF, on the author's call (2026-08-18: "quantize etme"). SS11.E's chain ends
in a snap to the 55 and this batch does not take it: the art is painted in its own muted
mauve-and-concrete range, and nearest-of-55 turns the parquet into speckle because the
floor's brown sits between Brick and Night with nothing in between. The step is kept
behind --quantize, palette still read from UITheme.cs (its one home, 14 v3 SS3, eleven
ramps of five asserted), so turning it back on is a flag and not a rewrite. What this
means downstream, said plainly: these assets are OFF-PALETTE by decision, so 14 SS3's
"every drawn pixel comes from here" now has a scene-art exception the bible should record.

SS11.B asks for flat #00FF00 panes and BANS a painted checkerboard. This batch shipped the
checkerboard anyway, so `key_checker` finds the panes by the pattern's own signature -- a
box where BOTH the white and the dusty pink appear is checker; a solid run of either is
paint, and paint stays. It is a rescue for one batch, not a licence: with a green key the
same job is one comparison.

The props arrive as SHEETS on white (two plants, three taps, two table arrangements per
tier), so `sheet` keys the white, splits on the empty columns between objects, and trims
each to its own alpha -- the same derive-don't-regenerate rule the bottles learned.

Commands:  measure [asset...]   report what the sources contain, ship nothing
           post    [asset...]   run the chain and write the assets
Sources:   %USERPROFILE%/Desktop/konsept art   (override with --src)
Log:       Tools/AssetPipeline/generation_log.jsonl (15 SS5)
"""
